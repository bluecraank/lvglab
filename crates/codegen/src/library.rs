//! Manifests that make the exported folder a library for PlatformIO
//! (`library.json`) and the Arduino IDE (`library.properties`).

use lvglab_model::Project;

use crate::output::{GeneratedFile, WritePolicy};
use crate::template::c_string;

pub fn manifests(project: &Project) -> Vec<GeneratedFile> {
    vec![
        GeneratedFile::text("library.json", library_json(project), WritePolicy::Overwrite),
        GeneratedFile::text("library.properties", library_properties(project), WritePolicy::Overwrite),
    ]
}

fn library_name(project: &Project) -> String {
    let name = project.export.library_name.trim();
    if name.is_empty() { "ui".to_owned() } else { name.to_owned() }
}

/// LVGL is not declared as dependency: the application provides it together
/// with its `lv_conf.h`, which avoids duplicate LVGL copies.
fn library_json(project: &Project) -> String {
    format!(
        "{{\n  \"name\": {},\n  \"version\": \"1.0.0\",\n  \"description\": {},\n  \"frameworks\": \"arduino\",\n  \"platforms\": \"espressif32\",\n  \"build\": {{\n    \"srcDir\": \"src\",\n    \"includeDir\": \"src\"\n  }}\n}}\n",
        c_string(&library_name(project)),
        c_string(&format!("UI of {} generated by LVGLab for LVGL {}", project.name, project.lvgl_version.suffix()))
    )
}

fn library_properties(project: &Project) -> String {
    format!(
        "name={}\nversion=1.0.0\nauthor=LVGLab\nmaintainer=LVGLab\nsentence=UI of {}\nparagraph=Generated for LVGL {}.\ncategory=Display\nurl=\narchitectures=esp32\ndepends=lvgl\n",
        library_name(project),
        project.name,
        project.lvgl_version.suffix()
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn manifests_use_library_name() {
        let mut project = Project::new("Demo");
        project.export.library_name = "dash_ui".into();
        let files = manifests(&project);
        assert!(files[0].contents_str().contains("\"name\": \"dash_ui\""));
        assert!(files[1].contents_str().starts_with("name=dash_ui\n"));
    }
}
